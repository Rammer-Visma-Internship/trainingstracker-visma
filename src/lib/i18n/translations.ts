export type TranslationKeys = typeof translations.en;

export function getTranslation(locale: Locale): TranslationKeys {
  return translations[locale] as unknown as TranslationKeys;
}

export function formatMessage(
  template: string,
  vars: Record<string, string | number>
): string {
  return Object.entries(vars).reduce(
    (msg, [key, value]) => msg.replace(`{${key}}`, String(value)),
    template
  );
}

export function getFormatLabel(
  locale: Locale,
  format: "in-person" | "online" | "self-paced"
): string {
  const t = getTranslation(locale).employee.logForm;
  switch (format) {
    case "in-person":
      return t.formatInPerson;
    case "online":
      return t.formatOnline;
    case "self-paced":
      return t.formatSelfPaced;
  }
}
